}


## Linters

# Clean mypy cache directories.
#
# Inspired by `ruff clean` on behaviour and output.
#
# Parameters:
#   1. Path where to clean (defaults to current directory).
mypy_clean() {
    local dest=${1:-.}

    for mcd in $(fd --hidden --no-ignore "${MYPY_CACHE_DIR:-.mypy_cache}" --type d "$dest"); do
        echo "Removing cache at: $mcd"
        rm -rf "$mcd"
    done
}


## Tools

# Get the path to the python packages installation.
get_py_sources() {
    any_pip show pip | grep 'Location:' | cut -d ' ' -f 2
}

# Grep in the list of installed packages.
grepip() {
    any_pip list | rg "$@"
}

