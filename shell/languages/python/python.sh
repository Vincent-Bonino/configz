# Python utils

## Create similar interface for pyenv/uv projects

is_uv_active() {
    ((UV_ACTIVE == 1))
}

any_pip() {
    if is_uv_active; then
        uv pip "$@"
    else
        pip "$@"
    fi
}


## Installation

# Install base packages for Python environment.
py_setup() {
    # === Variables ===
    local PIP_ENV=(setuptools wheel)

    local HOOKS=(colorama gitpython)
    local TOOLS=(ipython)

    local IFS=","

    # Environment
    if ! is_uv_active; then
        echo_blue "[i] Installing/updating pip,${PIP_ENV[*]}..."
        pip install -q -U pip
        pip install -q -U "${PIP_ENV[@]}"
    fi

    # Packages for git hooks
    echo_blue "[i] Installing/updating ${HOOKS[*]}..."
    any_pip install -q -U "${HOOKS[@]}"

    # Tools
    echo_blue "[i] Installing/updating ${TOOLS[*]}..."
    any_pip install -q -U "${TOOLS[@]}"
}

# Install python linters.
py_linters() {
    local LINTERS=(mypy yapf pylint pydocstyle pycodestyle isort autoflake ruff)

    any_pip install -U "${LINTERS[@]}"
}

# Install current project.
py_install() {
    py_setup

    if [[ -f "pyproject.toml" ]]; then
        echo_blue "[i] Install from pyproject.toml [all]"
        any_pip install -U '.[all]'
    else
        echo_orange "pyproject.toml not found"
    fi

    py_linters
}

# Uninstall installed packages.
py_uninstall() {
    >&2 echo_red "${FUNCNAME[0]} works poorly with editable and local installations"

    if is_uv; then
        uv pip freeze | cut -d " " -f 1 | grep -v "\-e" | xargs uv pip uninstall
    else
        pip freeze | cut -d " " -f 1 | grep -v "\-e" | xargs pip uninstall -q -y
    fi
}


